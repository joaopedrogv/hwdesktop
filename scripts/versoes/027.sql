CREATE OR ALTER PROCEDURE SP_REESTRUTURA_SNAPSHOT_SQL
returns (
    versao_script integer,
    nitem integer,
    versao_sistema varchar(10),
    build integer,
    opcoes varchar(64),
    execucao varchar(8),
    sqltext blob sub_type 1 segment size 256)
as
begin
  -- retorna os scripts que foram criados apos o snapshot
  for select
      rs.script_version, rs.script_seq
    from reestrutura_snapshot_scripts rs
    where rs.snapshot_id = (select max(snapshot_id) from reestrutura_snapshot_scripts)
    order by rs.script_version desc
      into :versao_script, :nitem
  do
  begin
    for select
        nitem, versao_sistema, build, opcoes, execucao, sqltext
      from reestrurura_sql
      where versao_script = :versao_script
        and nitem > :nitem
      order by nitem desc
        into :nitem, :versao_sistema, :build, :opcoes, :execucao, :sqltext
    do
      suspend;
  end
end;

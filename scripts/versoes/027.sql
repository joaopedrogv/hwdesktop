CREATE OR ALTER PROCEDURE SP_REESTRUTURA_ROLLBACK_LAST
returns (
    result varchar(32),
    versao integer,
    scripts integer)
as
  declare variable snapshotid integer;
  declare variable seqscript integer;
  declare variable manifest blob sub_type 1 segment size 1024;
begin
  result = 'success';

  snapshotid = null;

  for select first 1
      ss.id, ss.manifest
    from reestrutura_snapshot ss
    order by ss.id desc
      into :snapshotid, :manifest
  do
  begin
    for select
        sss.script_version, sss.script_seq
      from reestrutura_snapshot_scripts sss
      where sss.snapshot_id = :snapshotid
      order by sss.script_version desc, sss.script_version desc
        into :versao, :seqscript
    do
    begin
      select count(*) from reestrurura_sql rs
      where rs.versao_script = :versao
        and rs.nitem > :seqscript
        into :scripts;

      delete from reestrurura_sql rs
      where rs.versao_script = :versao
        and rs.nitem > :seqscript;
    
      update reestrurura_ver rv set
        rv.build = (
          select max(rs.build)
          from reestrurura_sql rs
          where rs.versao_script = :versao
        )
      where rv.versao_script = :versao;

      suspend;
    end
  end

  if (snapshotid = null) then
  begin
    result = 'snapshot-empty';
    suspend;
    exit;
  end

  update config_sistema cs set
    cs.value1_b = :manifest
  where cs.chave = 'reestrutura_manifest'
    and cs.cod_empresa = 0;

  delete from reestrutura_snapshot where id = :snapshotid;

  result = 'fim';
  scripts = null;
  versao = null;

  suspend;
end;

CREATE OR ALTER PROCEDURE SP_REESTRUTURA_SNAPSHOT_NEW
returns (
    result varchar(32),
    versao integer,
    sequencia integer)
as
  declare variable snapshotid integer;
  declare variable seqscript integer;
  declare variable manifest blob sub_type 1 segment size 1024;
  declare variable inserido smallint;
begin
  result = 'success';

  snapshotid = coalesce((select max(id) from reestrutura_snapshot), 0) + 1;
  inserido = 0;

  -- manifesto atual
  select cs.value1_b
  from config_sistema cs
  where cs.chave = 'reestrutura_manifest'
    and cs.cod_empresa = 0
    into :manifest;

  -- obtem registro mestre e sequencias do maior/ultimo por script
  for select
      rv.versao_script, max(rs.nitem)
    from reestrurura_ver rv
      left join reestrurura_sql rs on rs.versao_script = rv.versao_script
    where rv.versao_script >= 27
    group by 1
    order by rv.versao_script
      into :versao, :seqscript
  do
  begin
    --obten a sequencia da ultima versao
    select first 1
      s.script_seq
    from reestrutura_snapshot_scripts s
    where s.script_version = :versao
      order by s.snapshot_id desc
      into :sequencia;

    -- sequencia diferente entao registra
    if (coalesce(sequencia, 0) <> seqscript) then
    begin
      if (inserido <> 1) then
      begin
        -- snapshot do manifesto
        insert into reestrutura_snapshot
          (id, createdat, manifest)
        values
          (:snapshotid, current_timestamp, :manifest);
        inserido = 1;
      end
      -- insere snapshot do script caso o anterior seja diferente
      insert into reestrutura_snapshot_scripts
        (snapshot_id, script_version, script_seq)
      values (:snapshotid, :versao, :seqscript);


      sequencia = :seqscript;
      suspend;
    end
  end
end;

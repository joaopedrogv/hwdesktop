CREATE TABLE OP_FISCAIS_IBSCBS_COND (
    OP_FISCAIS_ID CHAR(36) NOT NULL,
    ATRIBUTO SMALLINT NOT NULL,
    VALOR SMALLINT NOT NULL,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_OP_FISCAIS_IBSCBS_COND
      PRIMARY KEY (OP_FISCAIS_ID, ATRIBUTO, VALOR),
    CONSTRAINT FK_OP_FISCAIS_IBSCBS_COND
      FOREIGN KEY (OP_FISCAIS_ID) REFERENCES OP_FISCAIS_IBSCBS (ID)
      ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT CK_OPF_IBSCBS_COND_ATRIB
      CHECK (ATRIBUTO IN (1, 2, 3)),
    CONSTRAINT CK_OPF_IBSCBS_COND_VALOR
      CHECK ((ATRIBUTO IN (1, 2) AND VALOR IN (1, 2))
             OR (ATRIBUTO = 3 AND VALOR BETWEEN 0 AND 6))
);

CREATE TABLE EVENTOS_DFE (
  ID              CHAR(36) NOT NULL,
  SEQID           INTEGER NOT NULL,
  FAMILIA_DOCUMENTO SMALLINT NOT NULL,
  TIPO_EVENTO     INTEGER NOT NULL,
  CHAVE_DOCUMENTO VARCHAR(50) NOT NULL,
  COD_EMPRESA     INTEGER NOT NULL,
  DATA_CADASTRO   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  DATA_ALTERACAO  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  ATIVO           SMALLINT DEFAULT 1,
  CONSTRAINT PK_EVENTOS_DFE PRIMARY KEY (ID),
  CONSTRAINT UNQ_EVENTOS_DFE_SEQ UNIQUE (COD_EMPRESA, SEQID),
  CONSTRAINT CHK_EVENTOS_DFE_FAMILIA CHECK (FAMILIA_DOCUMENTO > 0),
  CONSTRAINT CHK_EVENTOS_DFE_TIPO CHECK (TIPO_EVENTO > 0)
);

CREATE INDEX IDX_EVENTOS_DFE_EMP ON EVENTOS_DFE (COD_EMPRESA, ATIVO, FAMILIA_DOCUMENTO, TIPO_EVENTO);
CREATE INDEX IDX_EVENTOS_DFE_DOC ON EVENTOS_DFE (COD_EMPRESA, CHAVE_DOCUMENTO);

CREATE TABLE EVENTOS_DFE_112150 (
  EVENTO_DFE_ID          CHAR(36) NOT NULL,
  DATA_PREVISAO_ENTREGA  DATE NOT NULL,
  CONSTRAINT PK_EVENTOS_DFE_112150 PRIMARY KEY (EVENTO_DFE_ID),
  CONSTRAINT FK_EVENTOS_DFE_112150 FOREIGN KEY (EVENTO_DFE_ID)
    REFERENCES EVENTOS_DFE (ID) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE EVENTOS_DFE_211130_ITEM (
  ID             CHAR(36) NOT NULL,
  EVENTO_DFE_ID  CHAR(36) NOT NULL,
  NITEM          INTEGER NOT NULL,
  VIBS           NUMERIC(15,2) NOT NULL,
  VCBS           NUMERIC(15,2) NOT NULL,
  QIMOBILIZADO   NUMERIC(15,4) NOT NULL,
  UIMOBILIZADO   VARCHAR(6) NOT NULL,
  CONSTRAINT PK_EVENTOS_DFE_211130_ITEM PRIMARY KEY (ID),
  CONSTRAINT UNQ_EVENTOS_DFE_ITEM_NITEM UNIQUE (EVENTO_DFE_ID, NITEM),
  CONSTRAINT FK_EVENTOS_DFE_211130_ITEM FOREIGN KEY (EVENTO_DFE_ID)
    REFERENCES EVENTOS_DFE (ID) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT CHK_EVENTOS_DFE_ITEM_NITEM CHECK (NITEM BETWEEN 1 AND 990),
  CONSTRAINT CHK_EVENTOS_DFE_ITEM_VIBS CHECK (VIBS >= 0),
  CONSTRAINT CHK_EVENTOS_DFE_ITEM_VCBS CHECK (VCBS >= 0),
  CONSTRAINT CHK_EVENTOS_DFE_ITEM_QTD CHECK (QIMOBILIZADO >= 0),
  CONSTRAINT CHK_EVENTOS_DFE_ITEM_UNID CHECK (CHAR_LENGTH(UIMOBILIZADO) >= 1)
);
